export function buscarParlamentar(id: string): Parlamentar | undefined {
  return parlamentares.find((p) => p.id === id);
}

export function totalGastos(parlamentar: Parlamentar): number {
  return parlamentar.gastos.reduce((soma, g) => soma + g.valor, 0);
}

/** Média do gasto total entre todos os parlamentares do mock ("média da bancada"). */
export function mediaGastoBancada(): number {
  const total = parlamentares.reduce((soma, p) => soma + totalGastos(p), 0);
  return Math.round(total / parlamentares.length);
}
